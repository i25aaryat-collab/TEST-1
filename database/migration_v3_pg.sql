-- v3: lifestyle quiz, private phone sharing, flat shortlists + poll, Roomie Pact (PostgreSQL / Supabase)
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS q_clean SMALLINT CHECK (q_clean BETWEEN 0 AND 4),
  ADD COLUMN IF NOT EXISTS q_quiet SMALLINT CHECK (q_quiet BETWEEN 0 AND 4),
  ADD COLUMN IF NOT EXISTS q_meals SMALLINT CHECK (q_meals BETWEEN 0 AND 4),
  ADD COLUMN IF NOT EXISTS q_guests SMALLINT CHECK (q_guests BETWEEN 0 AND 4),
  ADD COLUMN IF NOT EXISTS q_chores SMALLINT CHECK (q_chores BETWEEN 0 AND 4),
  ADD COLUMN IF NOT EXISTS household_note VARCHAR(300),
  ADD COLUMN IF NOT EXISTS phone VARCHAR(15);
CREATE TABLE IF NOT EXISTS phone_shares (
  sharer_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  viewer_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (sharer_id, viewer_id));
CREATE TABLE IF NOT EXISTS flat_groups (
  id SERIAL PRIMARY KEY, name VARCHAR(60) NOT NULL,
  created_by INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  poll_open SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS group_members (
  group_id INT NOT NULL REFERENCES flat_groups(id) ON DELETE CASCADE,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, user_id));
CREATE TABLE IF NOT EXISTS shortlist (
  group_id INT NOT NULL REFERENCES flat_groups(id) ON DELETE CASCADE,
  listing_id INT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  added_by INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, listing_id));
CREATE TABLE IF NOT EXISTS poll_votes (
  group_id INT NOT NULL REFERENCES flat_groups(id) ON DELETE CASCADE,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  listing_id INT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, user_id));
CREATE TABLE IF NOT EXISTS pacts (
  match_id INT PRIMARY KEY REFERENCES matches(id) ON DELETE CASCADE,
  rules TEXT NOT NULL, version INT NOT NULL DEFAULT 1,
  proposed_by INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  accepted_by INT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP);
